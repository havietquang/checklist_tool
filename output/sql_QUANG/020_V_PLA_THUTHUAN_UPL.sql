USE CATALOG IDENTIFIER(:curated);
USE SCHEMA tckh;

CREATE OR REPLACE VIEW v_pla_thuthuan_upl AS
SELECT
    A.TBLE, A.DATA_DATE, A.BRANCH_CODE, A.CUSTGROUP, A.CUSTGROUP_NAME,
    A.KPI_CODE, A.KH_HE_THONG, A.KH_KHOI, A.UPL_DATE, A.CDR_DT_ID,
    B.KPI_LV1_G, B.KPI_LV1, B.KPI_LV2, B.KPI_LV2_1, B.KPI_LV3
FROM PLA_THUTHUAN_UPL A
LEFT JOIN P_KPI_NAME_DIM_UPL B
    ON A.KPI_CODE  = B.KPI_CODE
   AND A.DATA_DATE >= B.START_DATE
   AND A.DATA_DATE <= B.END_DATE;